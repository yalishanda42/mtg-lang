"""Write docs/bg-sample.md: every sample card in Ivanchev and modern Bulgarian, numbered for feedback."""
from pathlib import Path

from mtglang.realize.bg import load_sample, render_card_bg

root = Path(".")
out = ["# Bulgarian sample", "", "Generated by `scripts/bg_sample.py`. Line numbers (e.g. `7.2`) are for feedback.", ""]
for k, ref in enumerate(load_sample(root), 1):
    faces = render_card_bg(root, ref)
    out.append(f"## {k}. {faces[0].old.name}  (`{ref}`)")
    out.append("")
    for f in faces:
        if f is not faces[0]:
            out += ["", f"**// {f.old.name}**", ""]
        out.append(f"*{f.old.type_line}*" + (f" — {f.stats}" if f.stats else ""))
        out.append("")
        for i, (old, new) in enumerate(zip(f.old.lines, f.lines), 1):
            out.append(f"- `{k}.{i}` {old}  ")
            out.append(f"  <sub>{new}</sub>")
    out.append("")
Path("docs/bg-sample.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/bg-sample.md")
